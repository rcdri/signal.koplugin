# Generates emoji_data.go (emoji <-> :name:) from the Python "emoji" package.
import emoji
rows = []
seen = set()
for e, d in emoji.EMOJI_DATA.items():
    if d.get("status", 2) > 2:
        continue
    names = [d["en"]] + list(d.get("alias", []))
    names = [n.strip(":").lower() for n in names]
    aliases = [a.strip(":").lower() for a in d.get("alias", [])]
    good = [a for a in aliases if a[:1].isalpha()]
    disp = (good[0] if good else d["en"].strip(":").lower())
    rows.append((e, disp, names))
out = ["// Code generated by tools/gen_emoji.py from the Python emoji package. DO NOT EDIT.", "",
       "package main", "", "var emojiToName = map[string]string{"]
for e, disp, _ in rows:
    out.append("\t%s: %s," % (goq(e) if False else '"' + e.encode("unicode_escape").decode().replace("\\U", "\\U").replace("\\x", "\\u00") + '"', '"' + disp + '"'))
out.append("}")
out.append("")
out.append("var nameToEmoji = map[string]string{")
for e, disp, names in rows:
    for n in names:
        if n in seen:
            continue
        seen.add(n)
        out.append('\t"%s": "%s",' % (n.replace('"', '\\"'), e.encode("unicode_escape").decode().replace("\\x", "\\u00")))
out.append("}")
open("emoji_data.go", "w").write("\n".join(out) + "\n")
print(len(rows), "emoji,", len(seen), "names")
